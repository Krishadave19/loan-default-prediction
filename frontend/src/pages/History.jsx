import { useState, useMemo, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { motion } from 'framer-motion';
import {
  History as HistoryIcon,
  Search,
  Filter,
  Download,
  Trash2,
  Sparkles,
  PlusCircle,
  FileSpreadsheet,
  RotateCcw,
  ArrowUpDown,
  RefreshCw,
} from 'lucide-react';
import DashboardLayout from '../layouts/DashboardLayout';
import HistoryStats from '../components/history/HistoryStats';
import HistoryTable from '../components/history/HistoryTable';
import HistoryDetailModal from '../components/history/HistoryDetailModal';
import { usePredictionContext } from '../context/PredictionContext';
import { exportToCSV, exportToJSON } from '../services/historyService';

export default function History() {
  const {
    history = [],
    isHistoryLoading,
    refreshHistory,
    removeRecord,
    clearHistoryRecords,
    loadSampleHistory,
  } = usePredictionContext();

  // Automatically refresh history on mount and poll every 12 seconds so predictions by other users appear live
  useEffect(() => {
    refreshHistory();
    const interval = setInterval(() => {
      refreshHistory();
    }, 12000);
    return () => clearInterval(interval);
  }, [refreshHistory]);

  const [search, setSearch] = useState('');
  const [riskFilter, setRiskFilter] = useState('all');
  const [sortBy, setSortBy] = useState('newest');
  const [selectedRecord, setSelectedRecord] = useState(null);
  const [showClearConfirm, setShowClearConfirm] = useState(false);

  // Filter and sort records
  const filteredRecords = useMemo(() => {
    let result = [...history];

    // Filter by search query
    if (search.trim()) {
      const q = search.toLowerCase().trim();
      result = result.filter((r) => {
        const name = (r.applicant?.fullName || '').toLowerCase();
        const id = (r.id || '').toLowerCase();
        const purpose = (r.applicant?.LoanPurpose || '').toLowerCase();
        const emp = (r.applicant?.EmploymentType || '').toLowerCase();
        return name.includes(q) || id.includes(q) || purpose.includes(q) || emp.includes(q);
      });
    }

    // Filter by risk tier
    if (riskFilter !== 'all') {
      result = result.filter((r) => {
        const prob = r.result?.probability ?? r.result?.default_probability ?? 0;
        if (riskFilter === 'low') return prob < 0.25;
        if (riskFilter === 'medium') return prob >= 0.25 && prob < 0.50;
        if (riskFilter === 'high') return prob >= 0.50 && prob < 0.75;
        if (riskFilter === 'very_high') return prob >= 0.75;
        return true;
      });
    }

    // Sort
    result.sort((a, b) => {
      const timeA = new Date(a.timestamp || a.result?.scoredAt || 0).getTime();
      const timeB = new Date(b.timestamp || b.result?.scoredAt || 0).getTime();
      const probA = a.result?.probability ?? a.result?.default_probability ?? 0;
      const probB = b.result?.probability ?? b.result?.default_probability ?? 0;
      const amtA = a.applicant?.LoanAmount ?? 0;
      const amtB = b.applicant?.LoanAmount ?? 0;

      if (sortBy === 'oldest') return timeA - timeB;
      if (sortBy === 'prob_desc') return probB - probA;
      if (sortBy === 'prob_asc') return probA - probB;
      if (sortBy === 'amount_desc') return amtB - amtA;
      return timeB - timeA; // default newest
    });

    return result;
  }, [history, search, riskFilter, sortBy]);

  const handleClearHistory = () => {
    clearHistoryRecords();
    setShowClearConfirm(false);
  };

  return (
    <DashboardLayout
      badge="Predictive Intelligence Audit"
      title="Prediction History"
      subtitle="Track, filter, and audit every credit risk prediction and calibrated default probability score generated by the model."
    >
      {/* Overview Stats */}
      <HistoryStats records={history} />

      {/* Control / Filter Bar */}
      <div className="mt-8 space-y-4">
        <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
          {/* Search Input */}
          <div className="relative flex-1 max-w-md">
            <Search className="absolute left-3.5 top-1/2 h-4 w-4 -translate-y-1/2 text-ink-700/40 dark:text-white/40" />
            <input
              type="text"
              placeholder="Search by name, ID, loan purpose, employment…"
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full rounded-2xl border border-ink-900/10 bg-white/50 pl-10 pr-4 py-2.5 text-xs text-ink-900 placeholder:text-ink-700/40 focus:border-violet-500 focus:outline-none focus:ring-1 focus:ring-violet-500 dark:border-white/10 dark:bg-white/5 dark:text-white dark:placeholder:text-white/40"
            />
            {search && (
              <button
                onClick={() => setSearch('')}
                className="absolute right-3 top-1/2 -translate-y-1/2 text-xs text-ink-700/50 hover:text-ink-900 dark:text-white/50 dark:hover:text-white"
              >
                Clear
              </button>
            )}
          </div>

          {/* Action Buttons */}
          <div className="flex flex-wrap items-center gap-2">
            <Link
              to="/prediction"
              className="inline-flex items-center gap-1.5 rounded-full bg-accent-gradient px-4 py-2 text-xs font-semibold text-white shadow-glow transition-transform hover:-translate-y-0.5"
            >
              <PlusCircle className="h-3.5 w-3.5" />
              New Prediction
            </Link>

            <button
              onClick={() => refreshHistory()}
              disabled={isHistoryLoading}
              className="inline-flex items-center gap-1.5 rounded-full border border-violet-500/20 bg-violet-500/10 px-3.5 py-2 text-xs font-semibold text-violet-600 transition-colors hover:bg-violet-500/20 dark:text-violet-300"
              title="Sync latest prediction records from backend across all users"
            >
              <RefreshCw className={`h-3.5 w-3.5 ${isHistoryLoading ? 'animate-spin' : ''}`} />
              {isHistoryLoading ? 'Syncing...' : 'Sync Live'}
            </button>

            <button
              onClick={() => exportToCSV(filteredRecords)}
              disabled={filteredRecords.length === 0}
              className="inline-flex items-center gap-1.5 rounded-full border border-ink-900/10 bg-white/50 px-3.5 py-2 text-xs font-semibold text-ink-700 disabled:opacity-40 transition-colors hover:border-violet-400/50 hover:text-violet-600 dark:border-white/10 dark:bg-white/5 dark:text-white/70 dark:hover:text-violet-400"
            >
              <FileSpreadsheet className="h-3.5 w-3.5" />
              Export CSV
            </button>

            <button
              onClick={() => exportToJSON(filteredRecords)}
              disabled={filteredRecords.length === 0}
              className="inline-flex items-center gap-1.5 rounded-full border border-ink-900/10 bg-white/50 px-3.5 py-2 text-xs font-semibold text-ink-700 disabled:opacity-40 transition-colors hover:border-violet-400/50 hover:text-violet-600 dark:border-white/10 dark:bg-white/5 dark:text-white/70 dark:hover:text-violet-400"
            >
              <Download className="h-3.5 w-3.5" />
              JSON
            </button>

            {history.length > 0 && (
              <button
                onClick={() => setShowClearConfirm(true)}
                className="inline-flex items-center gap-1.5 rounded-full border border-rose-500/20 bg-rose-500/10 px-3.5 py-2 text-xs font-semibold text-rose-600 transition-colors hover:bg-rose-500/20 dark:text-rose-400"
              >
                <Trash2 className="h-3.5 w-3.5" />
                Clear All
              </button>
            )}

            {history.length === 0 && (
              <button
                onClick={loadSampleHistory}
                className="inline-flex items-center gap-1.5 rounded-full border border-violet-500/30 bg-violet-500/10 px-3.5 py-2 text-xs font-semibold text-violet-600 transition-colors hover:bg-violet-500/20 dark:text-violet-300"
              >
                <Sparkles className="h-3.5 w-3.5" />
                Load Sample History
              </button>
            )}
          </div>
        </div>

        {/* Filters and Sort Row */}
        <div className="flex flex-wrap items-center justify-between gap-3 border-y border-ink-900/5 py-3 dark:border-white/5">
          {/* Risk Level Filter Pills */}
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="mr-1 text-xs font-medium text-ink-700/50 dark:text-white/40">Filter:</span>
            {[
              { id: 'all', label: 'All Predictions' },
              { id: 'low', label: 'Low Risk (<25%)', color: 'text-emerald-600 dark:text-emerald-400' },
              { id: 'medium', label: 'Medium Risk (25-50%)', color: 'text-amber-600 dark:text-amber-400' },
              { id: 'high', label: 'High Risk (50-75%)', color: 'text-orange-600 dark:text-orange-400' },
              { id: 'very_high', label: 'Very High Risk (>75%)', color: 'text-rose-600 dark:text-rose-400' },
            ].map((tab) => (
              <button
                key={tab.id}
                onClick={() => setRiskFilter(tab.id)}
                className={`rounded-full px-3 py-1 text-xs font-semibold transition-all ${
                  riskFilter === tab.id
                    ? 'bg-accent-gradient text-white shadow-glow'
                    : 'bg-white/40 dark:bg-white/5 text-ink-700 dark:text-white/60 hover:text-ink-900 dark:hover:text-white border border-ink-900/5 dark:border-white/5'
                }`}
              >
                {tab.label}
              </button>
            ))}
          </div>

          {/* Sort Selector */}
          <div className="flex items-center gap-2">
            <ArrowUpDown className="h-3.5 w-3.5 text-ink-700/50 dark:text-white/40" />
            <select
              value={sortBy}
              onChange={(e) => setSortBy(e.target.value)}
              className="rounded-xl border border-ink-900/10 bg-white/50 px-3 py-1 text-xs font-medium text-ink-900 focus:outline-none dark:border-white/10 dark:bg-white/5 dark:text-white"
            >
              <option value="newest">Newest First</option>
              <option value="oldest">Oldest First</option>
              <option value="prob_desc">Risk: High to Low</option>
              <option value="prob_asc">Risk: Low to High</option>
              <option value="amount_desc">Loan Amount: High to Low</option>
            </select>
          </div>
        </div>
      </div>

      {/* Main Content Area */}
      <div className="mt-6">
        {history.length === 0 ? (
          /* Empty State */
          <motion.div
            initial={{ opacity: 0, y: 16 }}
            animate={{ opacity: 1, y: 0 }}
            className="glass glass-border-gradient rounded-3xl p-10 text-center max-w-xl mx-auto my-8"
          >
            <div className="mx-auto flex h-14 w-14 items-center justify-center rounded-2xl bg-accent-gradient text-white shadow-glow">
              <HistoryIcon className="h-7 w-7" />
            </div>
            <h3 className="mt-5 text-lg font-bold text-ink-900 dark:text-white">
              No Predictions Recorded Yet
            </h3>
            <p className="mt-2 text-xs leading-relaxed text-ink-700/60 dark:text-white/50 max-w-md mx-auto">
              Whenever you evaluate an applicant in the Predict engine, the full prediction, default probability,
              and SHAP factor attributions will be automatically saved here for audit and reporting.
            </p>
            <div className="mt-6 flex flex-wrap items-center justify-center gap-3">
              <Link
                to="/prediction"
                className="inline-flex items-center gap-2 rounded-full bg-accent-gradient px-5 py-2.5 text-xs font-bold text-white shadow-glow transition-transform hover:-translate-y-0.5"
              >
                <PlusCircle className="h-4 w-4" />
                Score Your First Applicant
              </Link>
              <button
                onClick={loadSampleHistory}
                className="inline-flex items-center gap-2 rounded-full border border-violet-500/30 bg-violet-500/10 px-5 py-2.5 text-xs font-semibold text-violet-600 transition-colors hover:bg-violet-500/20 dark:text-violet-300"
              >
                <Sparkles className="h-4 w-4" />
                Load Sample Applicants
              </button>
            </div>
          </motion.div>
        ) : filteredRecords.length === 0 ? (
          /* Search / Filter yielded no results */
          <div className="glass glass-border-gradient rounded-3xl p-8 text-center my-6">
            <p className="text-sm font-semibold text-ink-900 dark:text-white">
              No predictions matching "{search}" with filter "{riskFilter}"
            </p>
            <button
              onClick={() => {
                setSearch('');
                setRiskFilter('all');
              }}
              className="mt-3 inline-flex items-center gap-1.5 text-xs font-semibold text-violet-600 dark:text-violet-400 hover:underline"
            >
              <RotateCcw className="h-3.5 w-3.5" />
              Reset filters
            </button>
          </div>
        ) : (
          /* Table of records */
          <HistoryTable
            records={filteredRecords}
            onSelectRecord={(r) => setSelectedRecord(r)}
            onDeleteRecord={(id) => removeRecord(id)}
          />
        )}
      </div>

      {/* Record Audit Modal */}
      {selectedRecord && (
        <HistoryDetailModal
          record={selectedRecord}
          onClose={() => setSelectedRecord(null)}
          onDelete={(id) => removeRecord(id)}
        />
      )}

      {/* Clear Confirmation Modal */}
      {showClearConfirm && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
          <div
            className="fixed inset-0 bg-ink-900/60 backdrop-blur-sm"
            onClick={() => setShowClearConfirm(false)}
          />
          <div className="relative z-10 w-full max-w-md rounded-3xl border border-ink-900/10 bg-white p-6 shadow-2xl dark:border-white/10 dark:bg-navy-950">
            <h3 className="text-lg font-bold text-ink-900 dark:text-white">Clear All Prediction History?</h3>
            <p className="mt-2 text-xs leading-relaxed text-ink-700/60 dark:text-white/50">
              This will permanently delete all stored applicant scoring records from your browser and backend audit log. This action cannot be undone.
            </p>
            <div className="mt-6 flex items-center justify-end gap-3">
              <button
                onClick={() => setShowClearConfirm(false)}
                className="rounded-full border border-ink-900/10 px-4 py-2 text-xs font-semibold text-ink-700 dark:border-white/10 dark:text-white/70"
              >
                Cancel
              </button>
              <button
                onClick={handleClearHistory}
                className="rounded-full bg-rose-600 px-4 py-2 text-xs font-semibold text-white shadow-glow hover:bg-rose-700"
              >
                Yes, Clear All
              </button>
            </div>
          </div>
        </div>
      )}
    </DashboardLayout>
  );
}
